"""يكتب صفوف جدول studios في supabase/seed.sql من content/studios/*.json (ADR 0006 القرار 9).

    python -I scripts/sync-studios.py          # يعيد توليد الكتلة
    python -I scripts/sync-studios.py --check  # يفشل إن كانت الكتلة لا تطابق الوصفات (CI/الاختبارات)

- الكتلة بين `-- BEGIN studios (generated)` و`-- END studios (generated)` لا تُحرَّر يدويًا.
- pipeline = نص الوصفة كاملًا (JSON مضغوط بترتيب المفاتيح كما في الملف). cost_credits = null (التكلفة من النموذج).
- enabled يُقرأ من الكتلة الحالية لكل استوديو (التفعيل قرار يدوي بعد المجموعة الذهبية)، وافتراضه false.
- استوديو مذكور في الكتلة بلا ملف وصفة يبقى بسطره كما هو (ads-grid وugc إلى أن تُكتب وصفاتهما).
"""
import io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED = os.path.join(ROOT, 'supabase', 'seed.sql')
STUDIOS = os.path.join(ROOT, 'content', 'studios')
BEGIN = '-- BEGIN studios (generated by scripts/sync-studios.py — do not edit by hand)'
END = '-- END studios (generated)'

# بيانات العرض التي ليست في الوصفة (الأيقونة والشارة والترتيب والوصف)
META = {
    'product-shot': {'icon': 'shopping-bag', 'badge': 'جديد', 'sort': 1, 'description_ar': 'صور منتجات احترافية من صورة جوال عادية'},
    'ads-grid': {'icon': 'layout-grid', 'badge': 'رائج', 'sort': 2, 'description_ar': '9 صور إعلانية بنص عربي من لقطة واحدة'},
    'ugc': {'icon': 'user-plus', 'badge': 'Beta', 'sort': 3, 'description_ar': 'شخصية تتكلم بلهجة سعودية عن منتجك'},
}
# استوديوهات بلا وصفة بعد: صفها كما كان في seed المرحلة 0
PLACEHOLDERS = {
    'ads-grid': ('استوديو الإعلانات', '{"source":"content/studios/ads-grid.json"}', 12),
    'ugc': ('استوديو UGC', '{"source":"content/studios/ugc.json"}', 45),
}


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def current_enabled(seed_text):
    m = re.search(re.escape(BEGIN) + r'(.*?)' + re.escape(END), seed_text, re.S)
    out = {}
    if not m:
        return out
    for sid, enabled in re.findall(r"\(\s*'([a-z0-9-]+)',.*?,\s*(true|false),\s*\d+\s*\)", m.group(1), re.S):
        out[sid] = enabled == 'true'
    return out


def build_block(seed_text):
    enabled = current_enabled(seed_text)
    rows = []
    recipes = {}
    for name in sorted(os.listdir(STUDIOS)):
        if name.endswith('.json'):
            r = json.load(io.open(os.path.join(STUDIOS, name), encoding='utf-8'))
            recipes[r['id']] = r
    for sid in sorted(set(recipes) | set(PLACEHOLDERS), key=lambda s: META.get(s, {}).get('sort', 99)):
        meta = META.get(sid, {'icon': 'sparkles', 'badge': None, 'sort': 99, 'description_ar': ''})
        if sid in recipes:
            r = recipes[sid]
            name_ar = r['name_ar']
            pipeline = json.dumps(r, ensure_ascii=False, separators=(',', ':'))
            cost = 'null'
        else:
            name_ar, pipeline, cost_n = PLACEHOLDERS[sid]
            cost = str(cost_n)
        en = 'true' if enabled.get(sid, False) else 'false'
        badge = q(meta['badge']) if meta['badge'] else 'null'
        rows.append(f"  ({q(sid)}, {q(name_ar)}, {q(meta['description_ar'])}, {q(meta['icon'])}, {badge},\n   {q(pipeline)}::jsonb, {cost}, {en}, {meta['sort']})")
    body = (
        'insert into public.studios (id, name_ar, description_ar, icon, badge, pipeline, cost_credits, enabled, sort) values\n'
        + ',\n'.join(rows)
        + '\non conflict (id) do update set\n'
        '  name_ar = excluded.name_ar, description_ar = excluded.description_ar, icon = excluded.icon, badge = excluded.badge,\n'
        '  pipeline = excluded.pipeline, cost_credits = excluded.cost_credits, enabled = excluded.enabled, sort = excluded.sort;'
    )
    return f'{BEGIN}\n{body}\n{END}'


def main():
    seed = io.open(SEED, encoding='utf-8', newline='').read()
    block = build_block(seed)
    if BEGIN in seed:
        new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _m: block, seed, flags=re.S)
    else:
        # أول مرة: استبدال كتلة studios اليدوية القديمة
        m = re.search(r'(-- الاستوديو الأول[^\n]*\n)?insert into public\.studios .*?sort = excluded\.sort;', seed, re.S)
        if not m:
            sys.exit('could not find the studios insert in seed.sql')
        new = seed[: m.start()] + block + seed[m.end():]
    if '--check' in sys.argv:
        if new != seed:
            sys.exit('seed.sql studios block is out of date — run: python -I scripts/sync-studios.py')
        print('studios block up to date')
        return
    if new != seed:
        io.open(SEED, 'w', encoding='utf-8', newline='').write(new)
        print('seed.sql studios block updated')
    else:
        print('seed.sql studios block already up to date')


if __name__ == '__main__':
    main()
